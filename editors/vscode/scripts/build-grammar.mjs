// Builds syntaxes/megh.injection.tmLanguage.json.
//   node scripts/build-grammar.mjs
// Keep the directive lists in sync with packages/core/src/view/directives.ts.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** Directives that take (args) and open or continue a block. */
const CONTROL = ['if', 'elseif', 'unless', 'isset', 'foreach', 'for', 'while', 'session', 'can', 'cannot'];
/** Control directives used bare. */
const CONTROL_BARE = [
  'else', 'endif', 'endunless', 'endisset', 'endforeach', 'endfor', 'endwhile', 'break', 'continue',
  'auth', 'endauth', 'guest', 'endguest', 'endsession', 'endcan', 'endcannot',
];
/** Other built-ins that take (args). */
const BUILTIN = ['extends', 'section', 'yield', 'include', 'push', 'stack', 'component', 'slot', 'json', 'method'];
/** Other built-ins used bare. */
const BUILTIN_BARE = ['endsection', 'show', 'parent', 'endpush', 'endcomponent', 'endslot', 'csrf'];

// The lexer only sees a directive when "@" is not glued to a word
// (support@example.com stays text).
const NOT_GLUED = String.raw`(?<![\w@.])`;
const CONTROL_SCOPE = 'keyword.control.megh';
const BUILTIN_SCOPE = 'support.function.directive.megh';
const CUSTOM_SCOPE = 'entity.name.function.directive.megh';

const directiveCaptures = (scope) => ({
  1: { name: `${scope} punctuation.definition.directive.megh` },
  2: { name: scope },
});

/** Arguments are JavaScript; nested parens are balanced so `)` inside does not end them. */
const argumentsBody = {
  contentName: 'meta.embedded.megh.arguments source.js',
  patterns: [{ include: '#parens' }, { include: 'source.js' }],
};

const withArgs = (kind, scope, names, gap = String.raw`\s*`) => ({
  name: `meta.directive.${kind}.megh`,
  begin: String.raw`${NOT_GLUED}(@)(${names})${gap}(\()`,
  beginCaptures: {
    ...directiveCaptures(scope),
    3: { name: 'punctuation.section.arguments.begin.megh' },
  },
  end: String.raw`\)`,
  endCaptures: { 0: { name: 'punctuation.section.arguments.end.megh' } },
  ...argumentsBody,
});

const bare = (kind, scope, names) => ({
  name: `meta.directive.${kind}.megh`,
  match: String.raw`${NOT_GLUED}(@)(${names.join('|')})\b(?!\s*\()`,
  captures: directiveCaptures(scope),
});

const echo = (name, open, close, extra = '') => ({
  name,
  begin: open,
  end: close,
  beginCaptures: { 0: { name: `punctuation.section.embedded.begin.megh${extra}` } },
  endCaptures: { 0: { name: `punctuation.section.embedded.end.megh${extra}` } },
  contentName: 'meta.embedded.megh.expression source.js',
  patterns: [{ include: 'source.js' }],
});

const grammar = {
  $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
  name: 'Megh Template (injection)',
  scopeName: 'text.html.megh.injection',
  comment:
    'Generated by scripts/build-grammar.mjs; edit that file. Injected into every scope of text.html.megh (attribute values, <script>, <style>) except Megh\'s own embedded code and comments.',
  injectionSelector: 'L:text.html.megh -meta.embedded.megh -comment.block.megh',
  patterns: [
    { include: '#escapes' },
    { include: '#comment' },
    { include: '#raw-echo' },
    { include: '#echo' },
    { include: '#js-block' },
    { include: '#react-block' },
    { include: '#directives' },
    { include: '#bound-attribute' },
  ],
  repository: {
    // @{{ prints a literal "{{" (for Vue/Alpine), @@ a literal "@".
    escapes: {
      patterns: [
        { name: 'constant.character.escape.megh', match: String.raw`@\{\{` },
        { name: 'constant.character.escape.megh', match: '@@' },
      ],
    },
    comment: {
      name: 'comment.block.megh',
      begin: String.raw`\{\{--`,
      end: String.raw`--\}\}`,
      captures: { 0: { name: 'punctuation.definition.comment.megh' } },
    },
    'raw-echo': echo('meta.echo.raw.megh', String.raw`\{!!`, String.raw`!!\}`, ' keyword.operator.raw.megh'),
    echo: echo('meta.echo.megh', String.raw`\{\{`, String.raw`\}\}`),
    'js-block': {
      name: 'meta.directive.js.megh',
      begin: String.raw`${NOT_GLUED}(@)(js)\b`,
      end: String.raw`(@)(endjs)\b`,
      captures: directiveCaptures(BUILTIN_SCOPE),
      contentName: 'meta.embedded.megh.block.js source.js',
      patterns: [{ include: 'source.js' }],
    },
    // @react(props) <JSX module> @endreact
    'react-block': {
      name: 'meta.directive.react.megh',
      begin: String.raw`${NOT_GLUED}(@)(react)\b`,
      end: String.raw`(@)(endreact)\b`,
      captures: directiveCaptures(BUILTIN_SCOPE),
      patterns: [
        {
          begin: String.raw`\G\s*(\()`,
          beginCaptures: { 1: { name: 'punctuation.section.arguments.begin.megh' } },
          end: String.raw`\)`,
          endCaptures: { 0: { name: 'punctuation.section.arguments.end.megh' } },
          ...argumentsBody,
        },
        {
          begin: String.raw`(?<=\)|react)`,
          end: String.raw`(?=@endreact\b)`,
          contentName: 'meta.embedded.megh.block.jsx source.js.jsx',
          patterns: [{ include: 'source.js.jsx' }],
        },
      ],
    },
    directives: {
      patterns: [
        withArgs('control', CONTROL_SCOPE, CONTROL.join('|')),
        withArgs('builtin', BUILTIN_SCOPE, BUILTIN.join('|')),
        bare('control', CONTROL_SCOPE, CONTROL_BARE),
        bare('builtin', BUILTIN_SCOPE, BUILTIN_BARE),
        // Directives added with engine.directive(): only `@name(` with no
        // space, so CSS at-rules like `@media (` are left alone.
        withArgs('custom', CUSTOM_SCOPE, String.raw`[A-Za-z_]\w*`, ''),
      ],
    },
    parens: {
      begin: String.raw`\(`,
      end: String.raw`\)`,
      beginCaptures: { 0: { name: 'meta.brace.round.js' } },
      endCaptures: { 0: { name: 'meta.brace.round.js' } },
      patterns: [{ include: '#parens' }, { include: 'source.js' }],
    },
    // <x-alert :count="todos.length">: the value is a JavaScript expression.
    'bound-attribute': {
      name: 'meta.attribute.bound.megh',
      begin: String.raw`(?<=\s)(:)([\w-]+)\s*(=)\s*(")`,
      beginCaptures: {
        1: { name: 'punctuation.attribute-shorthand.bind.megh' },
        2: { name: 'entity.other.attribute-name.megh' },
        3: { name: 'punctuation.separator.key-value.html' },
        4: { name: 'string.quoted.double.html punctuation.definition.string.begin.html' },
      },
      end: '"',
      endCaptures: { 0: { name: 'string.quoted.double.html punctuation.definition.string.end.html' } },
      contentName: 'meta.embedded.megh.expression source.js',
      patterns: [{ include: 'source.js' }],
    },
  },
};

const out = fileURLToPath(new URL('../syntaxes/megh.injection.tmLanguage.json', import.meta.url));
writeFileSync(out, JSON.stringify(grammar, null, 2) + '\n');
console.log('wrote', out);
